import { useMemo, useRef } from 'react';

import { useScrollProgress, useReducedMotion } from '../lib/useScrollProgress.js';

/*
 * «О нас»: текст собирается из букв по мере прокрутки.
 *
 * Привязка к прокрутке, а не самостоятельный ход: крутишь вниз — текст
 * собирается, крутишь вверх — рассыпается обратно. Читатель управляет
 * сборкой сам.
 *
 * Задержка буквы растёт вместе с её местом в тексте, поэтому строки
 * проявляются сверху вниз, а не все разом: сначала первый абзац, потом
 * второй. Внутри одного места остаётся небольшой случайный разброс —
 * иначе буквы садились бы ровным строем, как курсор печатной машинки.
 *
 * Как это считается. В тексте больше тысячи букв. Пересчитывать положение
 * каждой на каждом кадре в React значило бы тысячу обновлений стиля за кадр.
 * Поэтому разброс задаётся букве один раз и живёт в её CSS-переменных,
 * а прокрутка меняет ровно одну переменную на всём блоке.
 */

const PARAGRAPHS = [
    'UNIVERSE design — студия, объединяющая искусство, технологии и инновации. Мы создаём медиаарт-инсталляции, которые трансформируют пространство, вовлекают зрителя и открывают новые границы восприятия.',
    'Наша ключевая специализация — волюметрические экраны и их нестандартное применение в искусстве, рекламе и event-пространствах. Мы не просто используем готовые решения, соответствующие стандартам, — мы экспериментируем с формами и разрабатываем авторские методы внедрения волюметрического экрана в масштабные проекты.',
    'Наши проекты — это не просто «экран с картинкой», а динамичная среда, где свет, объём и цифровое повествование становятся эмоциональным опытом. Мы верим, что медиаискусство — язык будущего, и находим для него неожиданные формы.',
];

const REASONS_TITLE = 'Почему мы?';

const REASONS = [
    'Глубокие технические знания: наша команда сочетает знания в области инженерии, программирования и медиадизайна, что позволяет создавать сложные инсталляции под ключ.',
    'Мы работаем с арт-галереями, музыкальными фестивалями, коммерческими брендами и архитектурными пространствами, адаптируя технологии под любые задачи.',
    'Исследовательский подход: тестируем новые способы взаимодействия — сенсоры, генеративный контент, — чтобы зритель стал частью инсталляции.',
    'Полный цикл производства: от концепции и 3D-визуализации до производства инсталляции и создания контента.',
];

/*
 * Насколько поздно может тронуться самая последняя буква.
 *
 * Эта величина и длительность полёта одной буквы в сумме обязаны давать
 * единицу — иначе поздние буквы не успевают долететь и текст остаётся
 * с дырами. Я наступал на это трижды, каждый раз правя одну половину
 * и забывая вторую, поэтому теперь длительность считается отсюда
 * и уезжает в CSS переменной. Развести их больше нельзя физически.
 */
const MAX_DELAY = 0.7;
export const LETTER_PHASE = 1 - MAX_DELAY;

const BLOCKS = [
    ...PARAGRAPHS.map((text) => ({ kind: 'p', text })),
    { kind: 'h', text: REASONS_TITLE },
    ...REASONS.map((text) => ({ kind: 'li', text })),
];

/** Весь текст одной строкой — для экранного диктора и поисковика. */
const PLAIN_TEXT = BLOCKS.map((b) => b.text).join(' ');

/**
 * Раскладывает блоки на слова, а слова на буквы, раздавая каждой букве
 * точку старта и очередь.
 *
 * Деление на слова обязательно: буква — это inline-block, и без обёртки
 * строка переносится в любом месте, получается «сту / дия».
 *
 * Разброс детерминированный, а не через Math.random: пререндер идёт в Node,
 * гидратация в браузере, и разные случайные числа дали бы рассинхрон разметки.
 */
function useScatteredBlocks(blocks) {
    return useMemo(() => {
        let seed = 20260809;
        const random = () => {
            seed = (seed * 1103515245 + 12345) % 2147483648;
            return seed / 2147483648;
        };

        const total = blocks.reduce((n, b) => n + b.text.length, 0);
        let seen = 0;

        return blocks.map((block, blockIndex) => ({
            kind: block.kind,
            key: `${blockIndex}-${block.kind}`,
            words: block.text.split(' ').map((word, wordIndex) => ({
                key: `${wordIndex}-${word}`,
                letters: [...word].map((char) => {
                    // Место буквы в общем потоке задаёт очередь: текст
                    // проявляется сверху вниз, а не весь разом.
                    const place = seen++ / total;

                    return {
                        char,
                        key: seen,
                        /*
                         * Разброс соразмерен кеглю, а не экрану.
                         *
                         * Когда абзац был один и набран крупно, буквы могли
                         * разлетаться на пол-экрана — их было полторы сотни,
                         * и каждая читалась отдельно. Теперь букв полторы
                         * тысячи и они мелкие: тот же разлёт превращал текст
                         * в метель, где не видно ни строк, ни слов.
                         *
                         * Буква отходит от своего места на десяток-другой
                         * пикселей — этого хватает, чтобы движение читалось
                         * как сборка, и текст при этом не теряется.
                         */
                        dx: Math.round((random() - 0.5) * 120),
                        dy: Math.round((random() - 0.5) * 90),
                        rotate: Math.round((random() - 0.5) * 90),
                        // Очередь плюс небольшой разброс внутри неё. Верхняя
                        // граница вместе с длительностью фазы в CSS даёт
                        // единицу — иначе поздние буквы не долетают.
                        delay: Math.min(
                            MAX_DELAY,
                            place * (MAX_DELAY - 0.08) + random() * 0.08,
                        ),
                    };
                }),
            })),
        }));
    }, [blocks]);
}

export function About() {
    const ref = useRef(null);
    const reducedMotion = useReducedMotion();

    // Прокрутка внутри раздела: вниз — собирается, вверх — рассыпается.
    const progress = useScrollProgress(ref);
    const blocks = useScatteredBlocks(BLOCKS);

    // Сборка укладывается в первые три четверти пути, дальше собранный текст
    // стоит — чтобы его успели дочитать, пока раздел не уехал.
    const eased = reducedMotion ? 1 : Math.min(1, progress / 0.75);

    return (
        <section className="section section--about" id="about" ref={ref}>
            <div className="section__inner">
                <div
                    className="assemble-block"
                    style={{ '--p': eased, '--phase': LETTER_PHASE }}
                    // Диктор читает текст целиком: для него сборка по буквам —
                    // это россыпь одиночных символов.
                    aria-label={PLAIN_TEXT}
                >
                    {blocks.map((block) => {
                        const Tag = block.kind === 'h' ? 'h2' : 'p';

                        return (
                            <Tag
                                className={`assemble assemble--${block.kind}`}
                                key={block.key}
                                aria-hidden="true"
                            >
                                {block.words.map((word) => (
                                    <span
                                        className="assemble__word"
                                        key={word.key}
                                    >
                                        {word.letters.map((letter) => (
                                            <span
                                                key={letter.key}
                                                className="assemble__letter"
                                                style={{
                                                    '--dx': `${letter.dx}px`,
                                                    '--dy': `${letter.dy}px`,
                                                    '--rot': `${letter.rotate}deg`,
                                                    '--delay': letter.delay,
                                                }}
                                            >
                                                {letter.char}
                                            </span>
                                        ))}
                                    </span>
                                ))}
                            </Tag>
                        );
                    })}
                </div>
            </div>
        </section>
    );
}
